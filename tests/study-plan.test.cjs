'use strict';
const assert = require('node:assert/strict');
const {record, resetProblem, mergeProgress, mergePlans} = require('../dist/study-plan.js');

let plan = {learned: {}, events: []};
plan = record(plan, 1, '2026-11-27');
assert.equal(plan.learned['1'].due, '2026-11-28');
assert.equal(plan.events[0].kind, 'new');
plan = record(plan, 1, '2026-11-28');
assert.equal(plan.learned['1'].due, '2026-11-29');
assert.equal(plan.events[1].kind, 'review');
plan = resetProblem(plan, 1);
assert.equal(plan.learned['1'], undefined);
assert.equal(plan.events.length, 2);
plan = record(plan, 1, '2026-11-28');
assert.equal(plan.learned['1'].stage, 0);
assert.equal(plan.learned['1'].due, '2026-11-29');
assert.equal(plan.events.length, 2);
const oldState = {accepted: [1], progressMeta: {}};
const resetState = {accepted: [], progressMeta: {'1': {solvedAt: 1, resetAt: 100}}};
assert.deepEqual(mergeProgress(oldState, resetState).accepted, []);
assert.deepEqual(mergeProgress({accepted: [1], progressMeta: {'1': {solvedAt: 101, resetAt: 100}}}, resetState).accepted, [1]);
const previousPlan = {learned: {'1': {stage: 0}}, events: [{id: '1', date: '2026-11-27'}]};
const resetPlan = {learned: {}, events: [], resetAt: 100};
assert.deepEqual(mergePlans(previousPlan, resetPlan).learned, {});
assert.deepEqual(mergePlans(previousPlan, resetPlan).events, []);
const deleted = resetProblem(previousPlan, 1, 200);
assert.deepEqual(mergePlans(previousPlan, deleted).learned, {});
assert.equal(mergePlans(previousPlan, deleted).events.length, 1);
console.log('study plan tests passed');
